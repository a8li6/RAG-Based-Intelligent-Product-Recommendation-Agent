def spec_sentence(title, ram, storage, weight, gpu) -> str:
    """Facts only, generated from the numeric fields so text cannot contradict data."""
    parts = []
    parts.append(f"{ram} GB RAM" if ram is not None else None)
    parts.append(f"a {storage} GB SSD" if storage is not None else None)
    known = [p for p in parts if p]
    sentence = f"{title} has " + (
        ", ".join(known[:-1]) + (" and " if len(known) > 1 else "") + known[-1]
        if known
        else "unlisted memory and storage"
    )
    if gpu is not None:
        sentence += f" with {gpu} graphics"
    sentence += "."
    missing = []
    if ram is None:
        missing.append("RAM size")
    if storage is None:
        missing.append("storage size")
    if weight is None:
        missing.append("weight")
    if gpu is None:
        missing.append("graphics type")
    if weight is not None:
        sentence += f" It weighs {weight:.2f} kg."
    if missing:
        sentence += " Not provided: " + ", ".join(missing) + "."
    return sentence


def record(pid, title, brand, cents, ram, storage, weight, gpu, stock, uses, blurb) -> dict:
    full_title = f"{title}" if brand == "DemoLab" else f"{brand} {title}"
    return {
        "product_id": pid,
        "title": full_title,
        "category": "laptop",
        "brand": brand,
        "price_cents": cents,
        "currency": "USD",
        "in_stock": stock,
        "ram_gb": ram,
        "storage_gb": storage,
        "weight_kg": weight,
        "gpu_type": gpu,
        "use_cases": uses,
        "description": f"{blurb} {spec_sentence(full_title, ram, storage, weight, gpu)}",
        "source_url": f"https://catalog.example/products/{pid}",
        "updated_at": UPDATED_AT,
    }


def build_records() -> list[dict]:
    fixture = [
        json.loads(line) for line in SAMPLE.read_text(encoding="utf-8").splitlines() if line.strip()
    ]
    authored = [record(*row) for row in ROWS]
    return sorted([*fixture, *authored], key=lambda r: r["product_id"])


def render(records: list[dict]) -> str:
    return "\n".join(json.dumps(r, ensure_ascii=False) for r in records) + "\n"


def main() -> None:
    records = build_records()
    OUT.write_text(render(records), encoding="utf-8")
    print(f"wrote {len(records)} records to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
